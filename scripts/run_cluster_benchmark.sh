#!/usr/bin/env bash
# Blocking versus asynchronous SEM_MAP against an OpenAI-compatible endpoint -- a vLLM deployment
# reached over an SSH tunnel, say. Generates the input and the test file, checks the endpoint,
# smoke-tests it, and only then runs the matrix.
#
#   ssh -L 8000:<vllm-host>:8000 <cluster>          # in another terminal, leave it open
#   scripts/run_cluster_benchmark.sh --model <served-model-id>
#
# The blocking path's concurrency is its worker thread count, not MAX_CONCURRENCY: it issues one
# request per record from an engine worker thread and blocks there, so its semaphore only binds
# below the thread count. That is why it is scanned over --threads while the asynchronous path is
# run once. See docs/design/20261006_async_operator_measurements.md, section 5.
set -euo pipefail

ENDPOINT=${ENDPOINT:-http://localhost:8000/v1}
MODEL=""
ROWS=${ROWS:-5000}
CONCURRENCY=${CONCURRENCY:-256}
THREADS=${THREADS:-"1 4 16 64 256"}
TIMEOUT_SECONDS=${TIMEOUT_SECONDS:-900}
MAX_RETRIES=${MAX_RETRIES:-3}
API_KEY_ENV=${API_KEY_ENV:-}
BUILD_DIR=${BUILD_DIR:-cmake-build-release}
SMOKE_ROWS=${SMOKE_ROWS:-12}

while [[ $# -gt 0 ]]; do
    case $1 in
        --model) MODEL=$2; shift 2 ;;
        --endpoint) ENDPOINT=$2; shift 2 ;;
        --rows) ROWS=$2; shift 2 ;;
        --concurrency) CONCURRENCY=$2; shift 2 ;;
        --threads) THREADS=$2; shift 2 ;;
        --api-key-env) API_KEY_ENV=$2; shift 2 ;;
        --build-dir) BUILD_DIR=$2; shift 2 ;;
        --smoke-only) SMOKE_ONLY=1; shift ;;
        *) echo "unknown argument '$1'" >&2; exit 1 ;;
    esac
done

SYSTEST=$BUILD_DIR/nes-systests/systest/systest
DATA_DIR=$BUILD_DIR/bench-data
SUITE=nes-systests/semantic
GENERATED=$SUITE/ClusterBenchmark.generated.test
PROBE=$SUITE/ClusterBenchmarkChecksum.generated.test

[[ -n $MODEL ]] || { echo "--model is required: the id vLLM serves, as /v1/models reports it" >&2; exit 1; }
[[ -x $SYSTEST ]] || { echo "systest not found at $SYSTEST; build it first (see --build-dir)" >&2; exit 1; }

# ---- 1. Is the endpoint there, and does it serve this model? ------------------------------------
echo "== checking $ENDPOINT"
served=$(curl -sS -m 15 "$ENDPOINT/models" ${API_KEY_ENV:+-H "Authorization: Bearer ${!API_KEY_ENV}"} \
    | python3 -c 'import json,sys; print(" ".join(m["id"] for m in json.load(sys.stdin).get("data", [])))') || {
    echo "cannot reach $ENDPOINT -- is the SSH tunnel open?" >&2; exit 1; }
echo "   serves: $served"
grep -qw -- "$MODEL" <<<"$served" || {
    echo "'$MODEL' is not among the served models; vLLM rejects a mismatched model id" >&2; exit 1; }

# ---- 2. Input ----------------------------------------------------------------------------------
echo "== generating $ROWS rows into $DATA_DIR"
scripts/generate_async_benchmark_data.py --out-dir "$DATA_DIR" --rows "$ROWS" --rows "$SMOKE_ROWS" >/dev/null

# ---- 3. The expected checksum, learned from the mock backend so it costs no model time ----------
# Only `id` is projected and nothing is filtered, so the expectation is independent of what the
# model answers. It asserts the property that matters: every record that goes in comes out.
emit_test() {
    local file=$1 rows=$2 backend=$3 endpoint=$4 model=$5 expected=$6 concurrency=$7
    cat > "$file" <<EOF
# name: semantic/$(basename "$file" .test)
# description: GENERATED by scripts/run_cluster_benchmark.sh -- do not edit, do not commit.
#              Blocking versus asynchronous SEM_MAP over $rows rows. Projecting only id and
#              filtering nothing makes the expectation independent of the model's answers, so it
#              asserts what matters for a throughput number: record count in == record count out.
# groups: [Semantic-Nightly]

CREATE LOGICAL SOURCE reviews(id UINT64 NOT NULL, reviewText VARSIZED NOT NULL);
CREATE PHYSICAL SOURCE FOR reviews TYPE File;
ATTACH FILE async/reviews_$rows.csv

CREATE SEMANTIC MODEL asyncModel
INPUT (reviewText VARSIZED)
OUTPUT (sentiment VARSIZED)
SET ('Classify the sentiment of the review as POSITIVE or NEGATIVE' AS LLM.PROMPT,
     '$endpoint' AS LLM.ENDPOINT, '$model' AS LLM.MODEL_NAME, '$backend' AS LLM.BACKEND,
     'POSITIVE,NEGATIVE' AS LLM.OUTPUT_VALUES, 'POSITIVE' AS LLM.DEFAULT_VALUE,
     $TIMEOUT_SECONDS AS LLM.TIMEOUT_SECONDS, $MAX_RETRIES AS LLM.MAX_RETRIES,${API_KEY_ENV:+ '$API_KEY_ENV' AS LLM.API_KEY_ENV,}
     'ASYNC' AS LLM.EXECUTION, 1 AS LLM.BATCH_SIZE, $concurrency AS LLM.MAX_CONCURRENCY);

CREATE SEMANTIC MODEL syncModel
INPUT (reviewText VARSIZED)
OUTPUT (sentiment VARSIZED)
SET ('Classify the sentiment of the review as POSITIVE or NEGATIVE' AS LLM.PROMPT,
     '$endpoint' AS LLM.ENDPOINT, '$model' AS LLM.MODEL_NAME, '$backend' AS LLM.BACKEND,
     'POSITIVE,NEGATIVE' AS LLM.OUTPUT_VALUES, 'POSITIVE' AS LLM.DEFAULT_VALUE,
     $TIMEOUT_SECONDS AS LLM.TIMEOUT_SECONDS, $MAX_RETRIES AS LLM.MAX_RETRIES,${API_KEY_ENV:+ '$API_KEY_ENV' AS LLM.API_KEY_ENV,}
     $concurrency AS LLM.MAX_CONCURRENCY);

CREATE SINK idsum(id UINT64 NOT NULL) TYPE Checksum;
CREATE SINK readingsOut(id UINT64 NOT NULL, value UINT64 NOT NULL) TYPE File;

CREATE LOGICAL SOURCE readings(id UINT64 NOT NULL, value UINT64 NOT NULL);
CREATE PHYSICAL SOURCE FOR readings TYPE File;
ATTACH FILE async/plain_200.csv

# Query 1: asynchronous, $concurrency calls in flight.
SELECT id FROM SEM_MAP(asyncModel, reviews) INTO idsum;
----
$expected

# Query 2: blocking. Its concurrency is the worker thread count, so this is run once per --threads.
SELECT id FROM SEM_MAP(syncModel, reviews) INTO idsum;
----
$expected

# Query 3: no model anywhere. Run beside query 1 and beside query 2 at the highest thread count,
# this is what shows what the blocking path costs the rest of the engine.
SELECT id, value FROM readings WHERE id > UINT64(189) INTO readingsOut;
----
$(python3 -c "print('\n'.join(f'{i},{i * 7 % 101}' for i in range(190, 201)))")
EOF
}

# Runs the same query against the mock backend, whose answers cost nothing, and reads the
# count-and-checksum pair out of the mismatch report. PLACEHOLDER never matches, which is the point.
learn_checksum() {
    local rows=$1
    emit_test "$PROBE" "$rows" mock echo mock-model PLACEHOLDER 4
    local pair
    pair=$("$SYSTEST" -t "$PWD/$PROBE:1" --workingDir "$BUILD_DIR/cluster-probe" --data "$DATA_DIR" --sequential 2>&1 \
        | sed -e 's/\x1b\[[0-9;]*m//g' | grep -oE '\| [0-9]+ [0-9]+$' | tail -1 | sed -e 's/^| //' -e 's/ /, /')
    if [[ -z $pair ]]; then
        echo "could not determine the expected checksum for $rows rows; the probe produced:" >&2
        "$SYSTEST" -t "$PWD/$PROBE:1" --workingDir "$BUILD_DIR/cluster-probe" --data "$DATA_DIR" --sequential 2>&1 | sed -e 's/\x1b\[[0-9;]*m//g' | grep -viE '^\[|RUST' | tail -12 >&2
        return 1
    fi
    rm -f "$PROBE"
    printf '%s' "$pair"
}

echo "== learning the expected checksums from the mock backend"
expected=$(learn_checksum "$ROWS")
expected_smoke=$(learn_checksum "$SMOKE_ROWS")
echo "   $ROWS rows -> $expected"
echo "   $SMOKE_ROWS rows -> $expected_smoke"

emit_test "$GENERATED" "$ROWS" http "$ENDPOINT" "$MODEL" "$expected" "$CONCURRENCY"

run() {
    local label=$1 threads=$2 concurrent=$3
    shift 3
    echo
    echo "=============================================================================="
    echo "$label  (worker threads: $threads, queries at once: $concurrent)"
    echo "=============================================================================="
    "$SYSTEST" --show-query-performance --workingDir "$BUILD_DIR/cluster" --data "$DATA_DIR" \
        -n "$concurrent" "$@" -- --worker.query_engine.number_of_worker_threads="$threads"
}

# ---- 4. Smoke test, so a wrong model id or a missing token fails in a minute, not in an hour ----
echo "== smoke test: $SMOKE_ROWS rows, concurrency 4"
SMOKE=$SUITE/ClusterBenchmarkSmoke.generated.test
emit_test "$SMOKE" "$SMOKE_ROWS" http "$ENDPOINT" "$MODEL" "$expected_smoke" 4
run "Smoke test, asynchronous" 4 1 -t "$PWD/$SMOKE:1" || {
    echo "smoke test failed -- fix that before spending model time on the matrix" >&2; exit 1; }
rm -f "$SMOKE"
[[ -z ${SMOKE_ONLY:-} ]] || { echo "smoke test passed; stopping as asked"; exit 0; }

# ---- 5. The matrix -----------------------------------------------------------------------------
run "Asynchronous, MAX_CONCURRENCY $CONCURRENCY" 4 1 -t "$PWD/$GENERATED:1"
for threads in $THREADS; do
    run "Blocking, $threads worker thread(s)" "$threads" 1 -t "$PWD/$GENERATED:2"
done

last_threads=${THREADS##* }
run "Asynchronous beside an unrelated query, 1 worker thread" 1 2 -t "$PWD/$GENERATED:1" "$PWD/$GENERATED:3"
run "Blocking beside an unrelated query, $last_threads worker thread(s)" "$last_threads" 2 \
    -t "$PWD/$GENERATED:2" "$PWD/$GENERATED:3"
run "The unrelated query on its own, for reference" 1 1 -t "$PWD/$GENERATED:3"

echo
echo "Divide $ROWS by each wall time for records per second. The generated test file is at"
echo "$GENERATED; it is not meant to be committed."
