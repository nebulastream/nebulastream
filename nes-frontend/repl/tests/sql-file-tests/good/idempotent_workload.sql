CREATE LOGICAL SOURCE IF NOT EXISTS endless(val_1 UINT32, ts UINT64);
CREATE PHYSICAL SOURCE IF NOT EXISTS FOR endless TYPE Generator SET(
    'ALL' as "SOURCE".STOP_GENERATOR_WHEN_SEQUENCE_FINISHES,
    'CSV' as INPUT_FORMATTER."TYPE",
    'SEQUENCE UINT32 0 10000000 1, SEQUENCE UINT64 0 10000000 1' AS "SOURCE".GENERATOR_SCHEMA);
CREATE QUERY IF NOT EXISTS endless_ts AS SELECT TS FROM ENDLESS INTO Void('localhost:8080' AS "SINK"."HOST");
