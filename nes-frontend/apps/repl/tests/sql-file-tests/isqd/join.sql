-- The join is placed on base-1; moving leaf-1 to base-2 moves it to sink-node, the only common downstream worker, and migrates its state.
CREATE WORKER 'sink-node:8080' SET ('sink-node:9090' AS DATA);
CREATE WORKER 'base-1:8080' SET ('base-1:9090' AS DATA, 3 AS MAX_OPERATORS, 'sink-node:8080' AS DOWNSTREAM);
CREATE WORKER 'base-2:8080' SET ('base-2:9090' AS DATA, 3 AS MAX_OPERATORS, 'sink-node:8080' AS DOWNSTREAM);
CREATE WORKER 'leaf-1:8080' SET ('leaf-1:9090' AS DATA, 0 AS MAX_OPERATORS, 'base-1:8080' AS DOWNSTREAM);
CREATE WORKER 'leaf-2:8080' SET ('leaf-2:9090' AS DATA, 0 AS MAX_OPERATORS, 'base-1:8080' AS DOWNSTREAM);
CREATE LOGICAL SOURCE stream(id UINT64);
CREATE LOGICAL SOURCE stream2(id2 UINT64);
CREATE PHYSICAL SOURCE FOR stream TYPE Generator SET(
       'ALL' AS "SOURCE".STOP_GENERATOR_WHEN_SEQUENCE_FINISHES,
       'CSV' AS INPUT_FORMATTER."TYPE",
       'leaf-1:8080' AS "SOURCE"."HOST",
       'emit_rate 1000' AS "SOURCE".GENERATOR_RATE_CONFIG,
       1 AS "SOURCE".SEED,
       'SEQUENCE UINT64 0 5000 1' AS "SOURCE".GENERATOR_SCHEMA);
CREATE PHYSICAL SOURCE FOR stream2 TYPE Generator SET(
       'ALL' AS "SOURCE".STOP_GENERATOR_WHEN_SEQUENCE_FINISHES,
       'CSV' AS INPUT_FORMATTER."TYPE",
       'leaf-2:8080' AS "SOURCE"."HOST",
       'emit_rate 1000' AS "SOURCE".GENERATOR_RATE_CONFIG,
       1 AS "SOURCE".SEED,
       'SEQUENCE UINT64 0 5000 1' AS "SOURCE".GENERATOR_SCHEMA);
CREATE SINK snk(LID UINT64, RID UINT64) TYPE File SET('out.csv' AS "SINK".FILE_PATH, 'CSV' AS "SINK".OUTPUT_FORMAT, 'sink-node:8080' AS "SINK"."HOST");
SELECT id AS lid, id2 AS rid FROM (SELECT * FROM (SELECT * FROM stream) INNER JOIN (SELECT * FROM stream2) ON id = id2 WINDOW TUMBLING (id, id2, size 100 ms)) INTO snk SET ('isqd-join' AS "QUERY"."ID");
