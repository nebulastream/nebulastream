"""Generates src/UnicodeTables.hpp, the Unicode data that utf8proc does not provide, from the CPython that runs this script.

The INLINE str methods take the general category, the bidirectional class, the simple case mappings and the case folding
from utf8proc, and these properties from the generated tables, so that they give the results of CPython's str methods:
- the characters that str.isdigit() and str.isnumeric() accept besides the decimal digits and the numbers (category N),
- XID_Start and XID_Continue, for str.isidentifier(),
- Lowercase and Uppercase, for str.islower(), str.isupper() and the case of a character,
- the case mappings that give more than one character, e.g. 'ß'.upper() == 'SS',
- the zero of each run of decimal digits, for int() and float(),
- the assigned code points: utf8proc may know a newer Unicode version than CPython, and its new characters are then
  unassigned, as in CPython.

Run it with the CPython version that the IN_PROCESS and OUT_OF_PROCESS executions use:
    python3 generate_tables.py > src/UnicodeTables.hpp
"""

import sys
import unicodedata

MAX_CODE_POINT = 0x10FFFF


def assigned(code_point: int) -> bool:
    return unicodedata.category(chr(code_point)) not in ("Cn", "Cs")


def ranges(predicate) -> list[tuple[int, int]]:
    result = []
    start = None
    for code_point in range(MAX_CODE_POINT + 2):
        inside = code_point <= MAX_CODE_POINT and assigned(code_point) and predicate(chr(code_point))
        if inside and start is None:
            start = code_point
        elif not inside and start is not None:
            result.append((start, code_point - 1))
            start = None
    return result


def emit_ranges(name: str, values: list[tuple[int, int]]) -> None:
    print(f"inline constexpr std::array<CodePointRange, {len(values)}> {name}{{{{")
    for first, last in values:
        print(f"    {{0x{first:X}, 0x{last:X}}},")
    print("}};")
    print()


def special_casing() -> list[tuple[int, int, list[int]]]:
    """(code point, kind, mapping) for each mapping to more than one character. kind: 0 lower, 1 upper, 2 title."""
    result = []
    for code_point in range(MAX_CODE_POINT + 1):
        if not assigned(code_point):
            continue
        character = chr(code_point)
        for kind, mapped in enumerate((character.lower(), character.upper(), character.title())):
            if len(mapped) > 1:
                result.append((code_point, kind, [ord(c) for c in mapped]))
    return result


print("/*")
for line in open(__file__).read().split('"""')[0].splitlines():
    print("   " + line[1:] if line.startswith("#") else line)
print("*/")
print()
print(f"/// Generated by generate_tables.py with Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}. Do not edit.")
print()
print("#pragma once")
print()
print("#include <array>")
print("#include <cstdint>")
print()
print("namespace NES::Unicode")
print("{")
print(f'inline constexpr const char* tablesUnicodeVersion = "{unicodedata.unidata_version}";')
print()
print("struct CodePointRange")
print("{")
print("    int32_t first;")
print("    int32_t last;")
print("};")
print()
emit_ranges("assigned", ranges(lambda c: True))
emit_ranges("digitBesidesDecimal", ranges(lambda c: c.isdigit() and not c.isdecimal()))
emit_ranges("numericBesidesCategoryN", ranges(lambda c: c.isnumeric() and unicodedata.category(c)[0] != "N"))
emit_ranges("lowercase", ranges(lambda c: c.islower()))
emit_ranges("uppercase", ranges(lambda c: c.isupper()))
emit_ranges("xidStart", ranges(lambda c: c.isidentifier()))
emit_ranges("xidContinue", ranges(lambda c: ("a" + c).isidentifier()))
zeros = [cp for cp in range(MAX_CODE_POINT + 1) if assigned(cp) and unicodedata.decimal(chr(cp), -1) == 0]
print(f"inline constexpr std::array<int32_t, {len(zeros)}> decimalZeros{{{{")
print("    " + ", ".join(f"0x{cp:X}" for cp in zeros))
print("}};")
print()
print("struct SpecialCasing")
print("{")
print("    int32_t codePoint;")
print("    int32_t kind;")
print("    std::array<int32_t, 3> mapping;")
print("    int32_t length;")
print("};")
print()
entries = special_casing()
assert all(len(mapping) <= 3 for _, _, mapping in entries)
print(f"inline constexpr std::array<SpecialCasing, {len(entries)}> specialCasing{{{{")
for code_point, kind, mapping in entries:
    padded = mapping + [0] * (3 - len(mapping))
    print(f"    {{0x{code_point:X}, {kind}, {{{{{', '.join(f'0x{c:X}' for c in padded)}}}}}, {len(mapping)}}},")
print("}};")
print("}")
