"""Runs out-of-process UDF benchmarks with pinned threads and processes and records every run.

    python3 run_experiment.py --experiment E20 --format native --udfs inc,lcg --layouts "P w7 p7" "Dw w3 p5" --reps 3

Each run executes one generated query through systest on a single-node topology and appends one JSON
line to ../results/<experiment>.jsonl: the commit of the code under test, the full command line, the layout, the inputs and the
measurements. It refuses to run with uncommitted changes, so that the commit says what was measured; describe the experiment and
its outcome in the shared experiment log afterwards: https://claude.ai/artifact/FbNXQThUuqEZEQQNNkEDJK

A layout says where things run on a machine with 16 hardware threads per NUMA node, even CPUs first thread of a core, odd CPUs
its sibling: `perf` are the performance CPUs (worker threads, one each), `misc` the CPUs of the source and other threads, `py`
the CPUs of the UDF processes (one each). --list prints all layouts.
"""

import argparse
import glob
import json
import os
import platform
import shutil
import subprocess
import sys
import threading
import time

HARNESS = os.path.dirname(os.path.abspath(__file__))
REPOSITORY = os.path.abspath(os.path.join(HARNESS, "..", "..", ".."))
RESULTS = os.path.join(HARNESS, "..", "results")
CORES = [0, 2, 4, 6, 8, 10, 12, 14]

# The inputs by name: file below --data and rows. `default` is the input of a UDF unless --input names another.
INPUTS = {
    "csv": {
        "files": {"30m": ("udf/udf_bench.csv", 30e6), "120m": ("udf/udf_bench_120m.csv", 120e6)},
        "default": {"inc": "120m", "upper": "120m", "lcg": "30m", "scan": "120m", "native_inc": "120m"},
        "schema": "id INT64 NOT NULL, s VARSIZED NOT NULL",
        "source_options": [],
    },
    "native": {
        "files": {"60m": ("udf/ids_60m.bin", 60e6), "480m": ("udf/ids_480m.bin", 480e6), "1920m": ("udf/ids_1920m.bin", 1920e6)},
        "default": {"inc": "480m", "lcg": "60m", "scan": "480m", "native_inc": "480m"},
        "schema": "id INT64 NOT NULL",
        "source_options": ["'NATIVE' AS INPUT_FORMATTER.\"TYPE\""],
    },
}

UDFS = {
    "inc": ("x INT64", "INT64", "    return x + 1", "id"),
    "upper": ("x VARSIZED", "VARSIZED", "    return x.upper()", "s"),
    "lcg": ("x INT64", "INT64", "    h = x\n    for _ in range(100):\n        h = (h * 1103515245 + 12345) % 2147483648\n    return h", "id"),
}

# Chained calls, which the optimizer cannot fuse: each call reads the result of the one before, so each gets a UDF operator of its
# own. Name: the UDFs of the calls, innermost first.
CHAINS = {"inc2": ["inc", "inc"], "inc3": ["inc", "inc", "inc"], "lcg2": ["lcg", "lcg"], "inclcg": ["inc", "lcg"], "lcginc": ["lcg", "inc"]}


def chain(udf):
    """The UDFs of the calls of a chain, innermost first, or None. `a+b+c` is a chain of any length, e.g. inc+lcg+inc."""
    if udf in CHAINS:
        return CHAINS[udf]
    calls = udf.split("+")
    return calls if len(calls) > 1 and all(call in UDFS for call in calls) else None


# --wide k: the input udf/wide_<k>.bin of make_native_inputs.sh, whose rows have id and k more INT64 fields from the source
WIDE = {3: 480e6, 7: 240e6, 15: 120e6, 31: 60e6}


def write_test(path, input_format, udf, input_file, source_on_performance_cpu, sources, unused=0, unused_after=False, wide=0):
    """Writes the systest file of one run: a logical source with `sources` physical file sources and one query."""
    description = INPUTS[input_format]
    options = list(description["source_options"])
    if source_on_performance_cpu:
        options.append("'PERFORMANCE' AS \"SOURCE\".CPUS")
    physical = "CREATE PHYSICAL SOURCE FOR input TYPE File" + (f" SET({', '.join(options)})" if options else "") + ";\n"
    lines = ["# name: benchmark/generated.test", "# description: generated by run_experiment.py", "# groups: [benchmark]", ""]
    schema = description["schema"] + "".join(f", w{index + 1} INT64 NOT NULL" for index in range(wide))
    lines.append(f"CREATE LOGICAL SOURCE input({schema});")
    for _ in range(sources):
        lines.append(physical + f"ATTACH FILE {input_file}\n")
    # Fields that no UDF reads. An inner query creates them, so that they exist before the UDF operators and are in the buffer
    # that the worker shares with the UDF processes.
    # With unused_after the outer query creates them. The worker then computes them after the UDF operators, so they are in the
    # query but not in the buffer of the UDF.
    source = "input"
    later = ""
    if unused:
        fields = "".join(f", id + INT64({index + 1}) AS u{index + 1}" for index in range(unused))
        if unused_after:
            later = fields
        else:
            source = f"(SELECT id{fields} FROM input)"
    if udf in UDFS or chain(udf):
        # One function per call, so that a chain of different UDFs has different functions
        calls = chain(udf) or [udf]
        expression = UDFS[calls[0]][3]
        for index, call in enumerate(calls):
            parameters, result, body, _ = UDFS[call]
            lines.append(f"CREATE FUNCTION udf{index} ({parameters}) RETURNS {result} EXECUTION OUT_OF_PROCESS AS $python$\n{body}\n$python$;\n")
            expression = f"udf{index}({expression})" + (" + INT64(1)" if index + 1 < len(calls) else "")
        lines.append(f"SELECT *{later}, {expression} AS r FROM {source} INTO Void();\n----\n")
    elif udf == "scan":
        lines.append("SELECT * FROM input INTO Void();\n----\n")
    elif udf == "native_inc":
        lines.append(f"SELECT *, id + INT64(1) AS r FROM {source} INTO Void();\n----\n")
    else:
        raise SystemExit(f"unknown UDF {udf}")
    with open(path, "w") as file:
        file.write("\n".join(lines))


def node(number):
    """The first hardware thread of every core of a NUMA node."""
    return list(range(16 * number, 16 * number + 16, 2))


def layouts():
    out = []

    def add(name, perf, misc, py, src_perf=False, workers=None):
        # File sources on a performance CPU take the performance CPUs the worker threads leave free.
        out.append({"name": name, "w": workers or len(perf), "p": len(py), "perf": perf, "misc": misc, "py": py, "src_perf": src_perf})

    # A: file source on a core of its own, the UDF source and misc threads on another
    for w, p in [(5, 1), (4, 2), (3, 3), (2, 4), (1, 5)]:
        add(f"A w{w} p{p}", CORES[: w + 1], [CORES[w + 1]], CORES[w + 2 : w + 2 + p], src_perf=True)
    # B: both sources and misc share one hardware thread
    for w, p in [(6, 1), (5, 2), (4, 3), (3, 4), (2, 5), (1, 6)]:
        add(f"B w{w} p{p}", CORES[:w], [CORES[w]], CORES[w + 1 : w + 1 + p])
    # C: both sources and misc share one core, on both of its hardware threads
    for w, p in [(5, 2), (4, 3), (3, 4), (2, 5)]:
        add(f"C w{w} p{p}", CORES[:w], [CORES[w], CORES[w] + 1], CORES[w + 1 : w + 1 + p])
    # D: no core for sources and misc, they run on hyperthread siblings of worker cores (Dw) or of process cores (Dp)
    for w, p in [(6, 2), (5, 3), (4, 4), (3, 5)]:
        add(f"Dw w{w} p{p}", CORES[:w], [1, 3], CORES[w : w + p])
        add(f"Dp w{w} p{p}", CORES[:w], [13, 15], CORES[w : w + p])
    # E: worker threads on both hardware threads of their cores
    for wc, p in [(5, 2), (4, 3), (3, 4), (2, 5)]:
        add(f"E w{2 * wc} p{p}", [c + s for c in CORES[:wc] for s in (0, 1)], [CORES[wc], CORES[wc] + 1], CORES[wc + 1 : wc + 1 + p])
    # F: worker threads and processes on both hardware threads of their cores
    for wc, pc in [(5, 2), (4, 3), (3, 4), (2, 5)]:
        workers = [c + s for c in CORES[:wc] for s in (0, 1)]
        processes = [c + s for c in CORES[wc + 1 : wc + 1 + pc] for s in (0, 1)]
        add(f"F w{2 * wc} p{2 * pc}", workers, [CORES[wc], CORES[wc] + 1], processes)
    # G: few workers, many processes
    add("G w1 p7", [0], [1], CORES[1:])
    add("G w2 p6", [0, 1], [2, 3], CORES[2:])
    add("G w2 p12", [0, 1], [2, 3], [c + s for c in CORES[2:] for s in (0, 1)])
    # P: a worker thread and a process share each core, one on each hardware thread
    add("P w7 p7", CORES[:7], [14, 15], [c + 1 for c in CORES[:7]])
    add("P w8 p8", CORES, [14, 15], [c + 1 for c in CORES])
    # X: node 0 as before, extra processes on the cores of node 1
    add("X w2 p14", [0, 2], [1, 3], CORES[2:] + node(1))
    add("X w7 p8", CORES[:7], [14, 15], node(1))
    add("X w7 p15", CORES[:7], [14, 15], [c + 1 for c in CORES[:7]] + node(1))
    # R: the worker has node 0 to itself, the processes run on the cores of other nodes. Nodes 1-3 share the socket of node 0.
    for label, nodes in [("n1", [1]), ("n1-2", [1, 2]), ("n1-3", [1, 2, 3]), ("n4", [4]), ("n4-5", [4, 5]), ("n4-7", [4, 5, 6, 7]), ("n1-7", [1, 2, 3, 4, 5, 6, 7])]:
        processes = [cpu for number in nodes for cpu in node(number)]
        add(f"R w7 {label}", CORES[:7], [14, 15], processes)
        add(f"R w14 {label}", list(range(14)), [14, 15], processes)
    # S: as R, but every source thread has a core of its own: the UDF source on CPU 14 (misc), the file sources on the
    # performance CPUs the workers leave free. `S w6` is for one file source, `S w5` for two (--sources 2), `S w3` for four.
    for label, nodes in [("n4-5", [4, 5]), ("n4-7", [4, 5, 6, 7])]:
        processes = [cpu for number in nodes for cpu in node(number)]
        for workers in (6, 5, 3):
            add(f"S w{workers} {label}", CORES[:7], [14], processes, src_perf=True, workers=workers)
        # worker threads on both hardware threads of five cores, two file sources on cores of their own
        add(f"S w10 {label}", list(range(10)) + [10, 12], [14], processes, src_perf=True, workers=10)
    # S ... smt: as `S w6`, with a process on both hardware threads of every core of the nodes, to compare a logical with a
    # physical core per process. Node 1 and socket 1 (nodes 4-7) are the cores that do not slow down under load.
    for label, nodes in [("n4", [4]), ("n4-5", [4, 5]), ("n4-7", [4, 5, 6, 7]), ("n1,4-7", [1, 4, 5, 6, 7])]:
        cores = [cpu for number in nodes for cpu in node(number)]
        if label in ("n4", "n1,4-7"):
            add(f"S w6 {label}", CORES[:7], [14], cores, src_perf=True, workers=6)
        add(f"S w6 {label} smt", CORES[:7], [14], [cpu + thread for cpu in cores for thread in (0, 1)], src_perf=True, workers=6)
        # m4, m8: as `smt`, with 4 or 8 misc CPUs (CPU 14 and cores of node 1), so that the threads of the UDF sources of a
        # chain do not share one CPU
        if label in ("n4", "n4-7"):
            for misc in (4, 8):
                add(f"S w6 {label} smt m{misc}", CORES[:7], [14] + node(1)[: misc - 1], [cpu + thread for cpu in cores for thread in (0, 1)], src_perf=True, workers=6)
    # T w<W> p<P>: a free number of worker threads against a free number of processes, to find the best ratio. The worker has
    # socket 0: W worker threads and 4 file sources on the first hardware threads of the cores of nodes 0-3, misc on the next
    # core. The processes are on node 4 (socket 1): on cores of their own up to 8, on both hardware threads of the cores for 16.
    socket0 = [cpu for number in range(4) for cpu in node(number)]
    for workers in (1, 2, 3, 4, 6, 8, 12, 16, 20, 24):
        for processes in (1, 2, 4, 8, 16):
            cpus = node(4)[:processes] if processes <= 8 else [cpu + thread for cpu in node(4) for thread in (0, 1)]
            add(f"T w{workers} p{processes}", socket0[: workers + 4], [socket0[workers + 4]], cpus, src_perf=True, workers=workers)
    return out


def git(*arguments):
    return subprocess.run(["git", "-C", REPOSITORY, *arguments], capture_output=True, text=True, check=True).stdout.strip()


def sample_threads(process, threads):
    """Keeps the CPU time of every thread of the worker, by thread id and name."""
    while process.poll() is None:
        for task in glob.glob(f"/proc/{process.pid}/task/*"):
            try:
                with open(task + "/comm") as comm_file, open(task + "/stat") as stat_file:
                    comm = comm_file.read().strip()
                    fields = stat_file.read().rsplit(")", 1)[1].split()
                threads[(task.rsplit("/", 1)[1], comm)] = (int(fields[11]) + int(fields[12])) / os.sysconf("SC_CLK_TCK")
            except OSError:
                pass
        time.sleep(0.2)


def bind_pools(process, helper, node, bound):
    """Binds every buffer pool of the worker to a NUMA node (mbind with MPOL_BIND) as soon as it exists, with the helper pool_bind.c.

    The pool is shared memory, so the policy holds for the worker and all UDF processes. Automatic NUMA balancing does not scan
    memory with such a policy, so it no longer unmaps and moves the pages of the pool (E34). `bound` receives the bound files."""
    while process.poll() is None:
        for fd in glob.glob(f"/proc/{process.pid}/fd/*"):
            try:
                target = os.readlink(fd)
                if not target.startswith("/memfd:nes-buffers"):
                    continue
                identity = os.stat(fd).st_ino
            except OSError:
                continue
            if identity not in bound:
                bound[identity] = subprocess.run([helper, fd, node], check=False).returncode
        time.sleep(0.01)


def run(arguments, layout, udf, repetition, record_base):
    inputs = INPUTS[arguments.format]
    operators = len(chain(udf) or [udf])
    input_name = arguments.input or inputs["default"][(chain(udf) or [udf])[-1]]
    input_file, rows = inputs["files"][input_name]
    if arguments.wide:
        input_name, input_file, rows = f"wide_{arguments.wide}", f"udf/wide_{arguments.wide}.bin", WIDE[arguments.wide]
    rows *= arguments.sources
    label = f"{arguments.experiment}-{arguments.format}-{layout['name'].replace(' ', '-')}-{udf}-r{repetition}"
    run_dir = os.path.join(arguments.scratch, label)
    shutil.rmtree(run_dir, ignore_errors=True)
    os.makedirs(run_dir + "/work")
    test_file = os.path.join(run_dir, "generated.test")
    write_test(test_file, arguments.format, udf, input_file, layout["src_perf"], arguments.sources, arguments.unused, arguments.unused_after, arguments.wide)
    environment = dict(os.environ, RUN_DIR=run_dir, BOOT=os.path.join(HARNESS, "boot.py"), UDF_BENCH_PYTHON=arguments.python)
    environment.update(setting.split("=", 1) for setting in arguments.environment)
    if "UDF_BENCH_POOL_NODE" in environment:
        # The helper that binds the buffer pool, see bind_pools
        helper = os.path.join(arguments.scratch, "pool_bind")
        subprocess.run(["gcc", "-O2", "-o", helper, os.path.join(HARNESS, "pool_bind.c")], check=True)
    worker_arguments = [
        f"--worker.query_engine.number_of_worker_threads={layout['w']}",
        f"--worker.python_udf.processes={arguments.processes or layout['p']}",
        f"--worker.python_udf.process_venv={os.path.join(HARNESS, 'venv')}",
        f"--worker.python_udf.process_protocol={arguments.protocol}",
        f"--worker.default_query_execution.operator_buffer_size={arguments.buffer}",
        f"--worker.total_memory_in_bytes={arguments.memory}",
        "--worker.query_engine.cpu_pinning=true",
        "--worker.query_engine.performance_cpus=" + ",".join(map(str, layout["perf"])),
        "--worker.query_engine.misc_cpus=" + ",".join(map(str, layout["misc"])),
        "--worker.python_udf.process_cpus=" + ",".join(map(str, layout["py"])),
        *arguments.worker_argument,
    ]
    command = [
        os.path.join(arguments.build, "nes-systests/systest/systest"),
        "-t",
        f"{test_file}:1",
        "--data",
        arguments.data,
        "--workingDir",
        run_dir + "/work",
        "--log-path",
        run_dir + "/log.txt",
        "-b",
        "--sequential",
        "-c",
        os.path.join(HARNESS, "single-node.yaml"),
        "--",
        *worker_arguments,
    ]
    with open(run_dir + "/out.txt", "w") as output:
        process = subprocess.Popen(command, env=environment, stdout=output, stderr=subprocess.STDOUT)
        threads = {}
        sampler = threading.Thread(target=sample_threads, args=(process, threads))
        sampler.start()
        bound_pools = {}
        binder = None
        if "UDF_BENCH_POOL_NODE" in environment:
            binder = threading.Thread(target=bind_pools, args=(process, helper, environment["UDF_BENCH_POOL_NODE"], bound_pools))
            binder.start()
        return_code = process.wait()
        sampler.join()
        if binder is not None:
            binder.join()

    seconds = None
    for path in glob.glob(run_dir + "/work/**/BenchmarkResults.json", recursive=True):
        with open(path) as results:
            seconds = json.load(results)[0]["time"]
    statistics = []
    for path in glob.glob(run_dir + "/stats*.json"):
        try:
            with open(path) as file:
                statistics.append(json.load(file))
        except json.JSONDecodeError:
            pass  # a process that was killed before it wrote its statistics
    active = [s for s in statistics if s["first"] is not None]
    busy = [(s["process"] + s["answer"]) / max(s["last"] - s["first"], 1e-9) for s in active]
    batches = max(sum(s["batches"] for s in statistics), 1)
    processed = max(sum(s["rows"] for s in statistics), 1)
    # Between the first batch of any process and the last batch of any process; the clocks of the processes are one monotonic clock.
    steady_seconds = max(s["last"] for s in active) - min(s["first"] for s in active) if active else None
    # The rows of all processes by quarter second. The trimmed rate leaves out the warm-up after the first batch (processes that
    # start, the compiler of PyPy) and the end of the input, and uses whole quarter seconds only.
    series = {}
    for s in active:
        for bucket, count in s.get("series", {}).items():
            series[int(bucket)] = series.get(int(bucket), 0) + count
    trimmed = None
    rates = []
    if series:
        first_bucket = min(series) + 1 + int(arguments.warmup * 4)
        last_bucket = max(series) - 1 - int(arguments.cooldown * 4)
        rates = [series.get(bucket, 0) / operators * 4 / 1e6 for bucket in range(min(series), max(series) + 1)]
        window = [series.get(bucket, 0) for bucket in range(first_bucket, last_bucket + 1)]
        if len(window) >= 8:
            trimmed = sum(window) / operators / (len(window) / 4) / 1e6
    # By quarter second, summed over the processes: wake-ups sent to the worker, sleeps, and kernel time in seconds (the
    # difference of the kernel time of a process between two quarter seconds in which it had an event)
    events = {}
    for s in active:
        previous = None
        for bucket, (wakes, sleeps, kernel, _) in sorted((int(bucket), entry) for bucket, entry in s.get("events", {}).items()):
            entry = events.setdefault(bucket, [0, 0, 0.0])
            entry[0] += wakes
            entry[1] += sleeps
            if previous is not None:
                entry[2] += (kernel - previous[1]) / (bucket - previous[0])
            previous = (bucket, kernel)
    cpu = {}
    for (_, comm), value in threads.items():
        cpu.setdefault("worker" if comm.startswith("WorkerThread") else comm, []).append(value)

    record = dict(
        record_base,
        layout=layout,
        udf=udf,
        repetition=repetition,
        input=input_file,
        rows=rows,
        command=command,
        return_code=return_code,
        seconds=seconds,
        mrows_per_s=round(rows / seconds / 1e6, 2) if seconds else None,
        steady_seconds=round(steady_seconds, 3) if steady_seconds else None,
        # every row passes each UDF operator once
        steady_mrows_per_s=round(sum(s["rows"] for s in active) / operators / steady_seconds / 1e6, 2) if steady_seconds else None,
        # as steady_mrows_per_s, without the first --warmup and the last --cooldown seconds; None for runs shorter than 2 s more
        trimmed_mrows_per_s=round(trimmed, 2) if trimmed else None,
        warmup=arguments.warmup,
        cooldown=arguments.cooldown,
        mrows_per_s_by_quarter_second=[round(rate, 2) for rate in rates],
        events_by_quarter_second=[[bucket - min(events)] + [round(value, 4) for value in events[bucket]] for bucket in sorted(events)],
        unused_fields=arguments.unused,
        unused_after=arguments.unused_after,
        wide_fields=arguments.wide,
        udf_operators=operators,
        processes_per_operator=arguments.processes or layout["p"],
        sources=arguments.sources,
        input_name=input_name,
        rows_per_batch=round(processed / batches) if statistics else None,
        process_ns_per_row=round(sum(s["process"] for s in statistics) / processed * 1e9, 1) if statistics else None,
        answer_ns_per_batch=round(sum(s["answer"] for s in statistics) / batches * 1e9) if statistics else None,
        process_wait_fraction=round(sum(s["wait"] for s in active) / max(sum(s["last"] - s["first"] for s in active), 1e-9), 2) if active else None,
        process_busy=round(sum(busy) / len(busy), 2) if busy else None,
        process_busy_min=round(min(busy), 2) if busy else None,
        processes_reporting=len(statistics),
        # PyPy is slower in every compiled loop once cpyext is loaded (E46)
        cpyext_loaded=sum(1 for s in statistics if s.get("cpyext")),
        ctypes_loaded=sum(1 for s in statistics if s.get("ctypes")),
        # The return codes of the binding of each buffer pool (UDF_BENCH_POOL_NODE), 0 if it worked
        pools_bound=list(bound_pools.values()),
        worker_busy=round(sum(cpu.get("worker", [])) / (layout["w"] * seconds), 2) if seconds else None,
        source_threads_cpu=sorted(round(value / seconds, 2) for name, values in cpu.items() if name.startswith("DataSrc") for value in values) if seconds else None,
        misc_threads_cpu={name: round(sum(values) / seconds, 2) for name, values in cpu.items() if name in ("task-delayer", "net-sender", "net-receiver")} if seconds else None,
    )
    os.makedirs(RESULTS, exist_ok=True)
    with open(os.path.join(RESULTS, arguments.experiment + ".jsonl"), "a") as results:
        results.write(json.dumps(record) + "\n")
    print(
        "%-12s %-10s r%d  %8s M rows/s (steady %s, trimmed %s, %.1f s)  processes busy %s (min %s)  %s ns/row  workers busy %s  sources %s  rc %d"
        % (layout["name"], udf, repetition, record["mrows_per_s"], record["steady_mrows_per_s"], record["trimmed_mrows_per_s"], seconds or 0, record["process_busy"], record["process_busy_min"], record["process_ns_per_row"], record["worker_busy"], record["source_threads_cpu"], return_code),
        flush=True,
    )
    if not arguments.keep:
        shutil.rmtree(run_dir, ignore_errors=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--experiment", help="id of the experiment in the experiment log, e.g. E20; names the results file")
    parser.add_argument("--list", action="store_true", help="print the layouts and exit")
    parser.add_argument("--format", choices=sorted(INPUTS), default="native", help="input format (default: native)")
    parser.add_argument("--input", help="input by name instead of the default of the UDF: 30m, 120m (csv); 60m, 480m, 1920m (native)")
    parser.add_argument("--sources", type=int, default=1, help="physical file sources reading the input, each with a thread of its own (default: 1)")
    parser.add_argument("--udfs", default="inc,lcg", help="comma-separated UDFs: inc, upper (csv only), lcg, the chains inc2, inc3, lcg2, inclcg, lcginc or any a+b+c, e.g. inc+lcg+inc (udf1(udf0(id) + 1)), scan and native_inc (native only)")
    parser.add_argument("--layouts", nargs="+", default=[], metavar="NAME", help="layout names, see --list")
    parser.add_argument("--unused", type=int, default=0, help="INT64 fields that the query adds and no UDF reads (default: 0)")
    parser.add_argument("--wide", type=int, default=0, choices=sorted(WIDE), help="read rows with this many more INT64 fields from the source, which no UDF reads (native format)")
    parser.add_argument("--unused-after", action="store_true", help="create the --unused fields after the UDF, so that they are not in its buffer")
    parser.add_argument("--processes", type=int, help="processes per UDF operator (default: one per process CPU of the layout); they are pinned to the process CPUs in turn")
    parser.add_argument("--reps", type=int, default=1)
    parser.add_argument("--buffer", type=int, default=65536, help="operator_buffer_size in bytes (default: 65536)")
    parser.add_argument("--memory", type=int, default=4294967296, help="total_memory_in_bytes (default: 4 GiB)")
    parser.add_argument("--protocol", default="SHARED_MEMORY_ZERO_COPY")
    parser.add_argument("--python", default="/usr/bin/pypy3", help="interpreter of the UDF processes (default: /usr/bin/pypy3)")
    parser.add_argument("--build", default=os.path.join(REPOSITORY, "cmake-build-relwithdebinfo-libstdcxx-none"))
    parser.add_argument("--data", default="/dev/shm/nes-udf-perf-eval", help="directory with the inputs, on a RAM disk")
    parser.add_argument("--scratch", default="/tmp/nes-udf-experiments", help="directory for the files of the runs")
    parser.add_argument("--worker-argument", action="append", default=[], metavar="ARG", help="further worker configuration, e.g. --worker.x=y")
    parser.add_argument("--environment", action="append", default=[], metavar="NAME=VALUE", help="environment variable of the worker and the UDF processes, e.g. PYPY_GC_NURSERY=1M")
    parser.add_argument("--warmup", type=float, default=3.0, help="seconds after the first batch that trimmed_mrows_per_s leaves out (default: 3)")
    parser.add_argument("--cooldown", type=float, default=1.0, help="seconds before the last batch that trimmed_mrows_per_s leaves out (default: 1)")
    parser.add_argument("--note", default="", help="free text stored with every record")
    parser.add_argument("--keep", action="store_true", help="keep the files of the runs, e.g. the generated program and the logs")
    arguments = parser.parse_args()

    by_name = {layout["name"]: layout for layout in layouts()}
    if arguments.list:
        for layout in by_name.values():
            print("%-12s workers %-40s misc %-10s processes %s%s" % (layout["name"], layout["perf"], layout["misc"], layout["py"], "  (file source on a performance CPU)" if layout["src_perf"] else ""))
        return
    if not arguments.experiment or not arguments.layouts:
        parser.error("--experiment and --layouts are required")
    unknown = [name for name in arguments.layouts if name not in by_name]
    if unknown:
        parser.error(f"unknown layouts: {unknown}")
    # Results files grow while an experiment runs; they are not code under test.
    if git("status", "--porcelain", "--untracked-files=no", "--", REPOSITORY, f":(exclude){RESULTS}"):
        sys.exit("There are uncommitted changes. Commit them first, so that the recorded commit says what was measured.")

    binary = os.path.join(arguments.build, "nes-systests/systest/systest")
    record_base = {
        "experiment": arguments.experiment,
        "started": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "commit": git("rev-parse", "HEAD"),
        "branch": git("rev-parse", "--abbrev-ref", "HEAD"),
        "binary": binary,
        "binary_modified": time.strftime("%Y-%m-%dT%H:%M:%S%z", time.localtime(os.path.getmtime(binary))),
        "commit_time": git("log", "-1", "--format=%cI"),
        "format": arguments.format,
        "protocol": arguments.protocol,
        "buffer": arguments.buffer,
        "memory": arguments.memory,
        "python": subprocess.run([arguments.python, "--version"], capture_output=True, text=True, check=False).stdout.strip().replace("\n", " "),
        "kernel": platform.release(),
        "environment": arguments.environment,
        "note": arguments.note,
    }
    for name in arguments.layouts:
        for udf in arguments.udfs.split(","):
            for repetition in range(arguments.reps):
                run(arguments, by_name[name], udf, repetition, record_base)


if __name__ == "__main__":
    main()
